def clarifying_block(case_key: str) -> str:
    """Блок уточняющих вопросов под тип задачи, по одному вопросу на строку.

    Пустая строка, если для кейса вопросов нет — вызывающему не нужно проверять.
    """
    hints = CLARIFYING_HINTS.get(case_key)
    if not hints:
        return ""
    return CLARIFYING_HINT_BLOCK.format(clarifying_hint="\n".join(hints))

