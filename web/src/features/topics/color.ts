/**
 * Свой цвет каждой темы.
 *
 * Приложение намеренно монохромное — цвет в нём означает состояние, а не декор
 * (см. `--attention` в globals.css). Здесь единственное исключение, и у него
 * есть работа: кружок стоит на карточке в колоде и рядом с подписью внизу
 * экрана, и по нему видно, что кнопка заявки относится именно к той карточке,
 * которая сейчас наверху. Раньше это связывали только словами, а слова внизу
 * экрана не читают.
 *
 * Цвета неоновые: кружок маленький и лежит поверх фотографии, а приглушённые
 * оттенки на ней тонули — глаз за них не цеплялся, и весь смысл знака пропадал.
 * Каждый различим и на белом, и на тёмном: тема приложения меняется вместе с
 * клиентом Telegram.
 */

/**
 * Цвета закреплены за темами поимённо, а не выданы по порядку в колоде: порядок
 * правят в Supabase, и карточка не должна менять цвет от пересортировки —
 * человек запоминает «синяя карточка», а не «пятая».
 */
const BY_TOPIC: Record<string, string> = {
  unique: "#0a84ff", // синий
  reference: "#ff2d9e", // розовый
  curved: "#00e5ff", // голубой
  revit: "#7c4dff", // фиолетовый
  repeat: "#00e676", // зелёный
  variants: "#ff9500", // оранжевый
  physics: "#ffd60a", // жёлтый
  custom: "#ff375f", // алый
};

/** Запас для тем, которых ещё нет в таблице: те же неоновые оттенки. */
const FALLBACK = Object.values(BY_TOPIC);

export function topicColor(key: string): string {
  const known = BY_TOPIC[key];
  if (known) return known;
  // Хеш ключа даёт стабильный выбор: новая тема получает цвет и не меняет его
  // при каждой сборке.
  let hash = 0;
  for (let i = 0; i < key.length; i += 1) {
    hash = (hash * 31 + key.charCodeAt(i)) >>> 0;
  }
  return FALLBACK[hash % FALLBACK.length];
}
