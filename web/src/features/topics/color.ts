/**
 * Свой цвет каждой темы.
 *
 * Приложение намеренно монохромное — цвет в нём означает состояние, а не декор
 * (см. `--attention` в globals.css). Здесь единственное исключение, и у него
 * есть работа: кружок стоит на карточке в колоде и рядом с подписью внизу
 * экрана, и по нему видно, что кнопка заявки относится именно к той карточке,
 * которая сейчас наверху. Раньше это связывали только словами, а слова внизу
 * экрана не читают.
 *
 * Цвета приглушённые: рядом с ними живёт фотография карточки, и насыщенное
 * пятно перетягивало бы внимание на себя. Каждый различим на белом и на тёмном
 * — тема приложения меняется вместе с клиентом Telegram.
 */
const PALETTE = [
  "#c8453f", // кирпичный
  "#c9772a", // охра
  "#a8912b", // латунь
  "#4d8f5b", // хвойный
  "#3a8b96", // бирюзовый
  "#4667b0", // синий
  "#7a56b5", // фиолетовый
  "#b34a7d", // пурпурный
] as const;

/**
 * Цвет темы по её ключу.
 *
 * Не по порядку в колоде: порядок меняют в Supabase, и цвет карточки не должен
 * переезжать вместе с ним — человек запоминает «синяя карточка», а не «пятая».
 * Хеш ключа даёт стабильный выбор и работает для тем, которых ещё нет.
 */
export function topicColor(key: string): string {
  let hash = 0;
  for (let i = 0; i < key.length; i += 1) {
    hash = (hash * 31 + key.charCodeAt(i)) >>> 0;
  }
  return PALETTE[hash % PALETTE.length];
}
