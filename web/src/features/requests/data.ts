/**
 * Заявки пользователя и их вехи.
 *
 * В черновике выдуманы целиком: своих заявок отдела в ClickUp нет, а серверной
 * части, которая отдавала бы заявки конкретного человека, пока не существует —
 * для неё нужна проверка подписи `initData`.
 */

export const REQUEST_STAGES = [
  "Отправлена",
  "Принята",
  "В работе",
  "Результат",
] as const;

export type MyRequest = {
  id: string;
  title: string;
  /** Откуда заявка родилась — тема или конкретный материал. */
  originLabel: string;
  project: string;
  /** Индекс текущей вехи в REQUEST_STAGES. */
  stage: number;
  /**
   * Состояние, которое не является вехой: оно возвращает заявку назад, и
   * шкала вех такое показать не может — поэтому отдельным баннером.
   */
  flag?: "Требуется уточнение" | "На доработке";
  /** Чужая задача, на которую подписались, а не своя заявка. */
  watching?: boolean;
  when: string;
};

/**
 * Заявок в приложении пока нет.
 *
 * Чтобы показать заявки конкретного человека, нужно проверить подпись
 * `initData` — а это серверный код, которого у статического экспорта не
 * бывает. Массив пуст осознанно: профиль в этом случае отправляет человека в
 * чат бота, где список заявок работает (`/my`). Выдуманные карточки здесь
 * означали бы, что интерфейс врёт про состояние дел.
 *
 * Прототип с наполненным списком живёт в ветке `draft/miniapp-flow`.
 */
export const MY_REQUESTS: readonly MyRequest[] = [];

export function myRequestById(id: string): MyRequest | undefined {
  return MY_REQUESTS.find((r) => r.id === id);
}
