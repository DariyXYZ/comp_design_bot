/**
 * Оформленные материалы под темами отдела: кейсы, инструменты, модули.
 *
 * Названия проектов, задач и инструментов — настоящие, выгружены из ClickUp
 * (пространство Computational Design). Настоящие и темы карточек — они
 * приходят из Supabase, как в проде.
 *
 * Сверено с сетевым диском 3 сентября 2026. Скрипты под типом «Готовый
 * скрипт» — это реальное содержимое `Library\gh_definitions`: у каждого есть
 * определение, описание и превью, и всё перечисленное взято оттуда, а не
 * придумано. Прежние записи этого типа ссылались на папки, которых на диске
 * нет, и заменены.
 *
 * Пути к проектам сверены выборочно: те, где папка нашлась, ведут в неё
 * целиком; остальные (ЦентрЛаб, «Барка») остались прежними и требуют сверки.
 *
 * Данные лежат в модуле рядом с типами: когда появится таблица, экспортируемые
 * функции станут запросом, а форма ответа не изменится.
 */

export type MaterialType = "case" | "tool" | "module";

export type Material = {
  id: string;
  /** Ключ темы из таблицы `cases` — карточка деки, под которой лежит материал. */
  topic: string;
  type: MaterialType;
  title: string;
  /** Одна строка списка: чем это полезно. */
  summary: string;
  /** Проект IND, где решение уже применялось (у кейсов). */
  project?: string;
  /** Подпись под демо-медиа: в черновике вместо гифки серый блок. */
  media: string;
  /** Инструкция «сделай сам» — то, ради чего материал оформляют. */
  steps: readonly string[];
  /** Где лежат файлы. Это путь на сетевом диске, а не ссылка. */
  files: string;
  updated: string;
  /**
   * Обложка из папки решения, уже сжатая и положенная в `public/materials`.
   *
   * Есть там, где в папке лежит превью: у скриптов библиотеки это `image.jpg`
   * рядом с определением, у кейсов — вид из папки проекта. Где превью нет,
   * остаётся знак скрипта: рисовать картинку ради единообразия значило бы
   * показывать не то, что человек получит.
   */
  cover?: string;
};

/**
 * Как тип материала называется **для человека в приложении**.
 *
 * «Кейс / Инструмент / Модуль» — таксономия отдела: она отвечает на вопрос
 * «что это за артефакт». Архитектору важна другая ось — что он может с этим
 * сделать: повторить сделанное, взять готовый продукт отдела или вставить
 * готовый скрипт в своё определение. Поэтому в интерфейсе стоят эти подписи,
 * а не внутренние.
 *
 * Модуль сначала был подписан «Набор вариантов» — непонятно, вариантов чего.
 * По сути это готовый кусок алгоритма на одну операцию (маркировка панелей,
 * типизация, перебор паттерна), поэтому «Готовый скрипт» — и рядом на строке
 * уже стоит знак скрипта.
 */
